#!/usr/bin/env python3
"""The seam: a family and a leaf in, the directory those records live in TODAY out.

## What this is for

A caller names a KIND (a family and a leaf from `families.py`), never a path,
and one file on disk says where that kind's records live. A move of a kind is
a change to its manifest row (`state` to `moved`), never an edit to a caller.

## Reading and writing are NOT the same question

* **Writing is always answerable.** A new record of a given kind has exactly one
  correct destination. `write_dir()` always returns one directory.
* **Reading may not be.** A kind whose records sit in many directories has no
  single answer, so `read_dirs()` returns MANY directories and callers must not
  assume one. A single `resolve()` returning one Path would be quietly wrong
  for a spread kind; it does not exist here, and the choice is in the name.

## The manifest set

Two files, both generated by `manifest.py`, both under one directory:

`family-locations.tsv`: one row per family/leaf pair::

    family	leaf	current_dir	target_dir	state	files	spread_over_dirs

`current_dir` is the deepest directory containing every record of the pair,
relative to the data root, or `.` when that is the data root itself.
`spread_over_dirs` is how many distinct directories actually hold them.
`state` is `not-moved`, `moving`, `moved` or `not-for-migration`. The last two
are the two ways a kind is FINISHED; `not-for-migration` reads exactly like
`moving`, see `STATE_NOT_FOR_MIGRATION`.

`families.tsv`: one row per FILE::

    path	family	leaf	method	sensitivity	target

and beside them `manifest-report.json`, read for one field: the date the tables
were generated.

`read_dirs()` answers from the per-file table, because a per-family table
cannot place a spread pair. Rows out of the scheme by decision, rows with no
family yet and rows with the leaf still open are counted apart and travel on
every `ReadScope`, so a read never looks complete while omitting them. Once a
pair's state is `moved` the per-file table is not consulted for it.

Where the pair is read from, first hit wins:

  1. ``HEADING_OS_2_MANIFEST``: a directory holding both files, or the
     `family-locations.tsv` itself. Set-but-missing RAISES; it never falls
     through, same discipline as ``env_data_root()``.
  2. ``<data root>/_manifest/``: the permanent home.
  3. the directory the registry names ``ho2-migration-workdir``.

Every entry point takes an explicit `manifest=`; the search order is only the
default.

## Every failure is a refusal

This module must never return a plausible directory that is wrong: a wrong
directory gets created, written into, and found empty months later. So an
unknown family or leaf, a pair with no row, a missing or malformed manifest, a
row marked `moved` whose two directories disagree, and a `current_dir` that
would escape the data root are each refused, by name, with the line number.

`read_root()` refuses a single-directory answer for any pair whose spread is
greater than one, rather than returning the most populous directory (a
plurality vote looked right and was wrong, 2026-09-12).

`check_agreement()` holds the two generated tables against each other and
refuses on a split: a kind whose `target` in the per-file table is not the
`target_dir` in the per-family table, or a kind one table places and the other
does not. Every read runs it.

Age is REPORTED, never refused: `manifest_generated()` gives the date the
generator's report claims, and `read_files()` and `ReadScope` carry it
(operator ruling, 2026-09-13).

There is no fallback path here, unlike ``load_routing_map()``, which fails
closed to `private`: there a safe default exists, here every candidate default
is a directory, and a directory chosen without the answer is the defect.

## Caching

Both tables are parsed once per process, keyed on the file's IDENTITY
(absolute path, `st_mtime_ns`, `st_size`), so a rewritten manifest is a cache
miss on the very next call in a long-running process. A rewrite in the same
nanosecond with the same byte count is invisible to this key;
`invalidate_cache()` is there for a caller that needs certainty. A caller that
stores a resolved Path for hours is holding an answer, not asking a question:
call the resolver at the point of use.

## What it does NOT do

It does not create directories. Making the directory is the caller's business
at the moment it writes something.
"""
