class ManifestError(RuntimeError):
    """Base for every refusal in this module.

    A ``RuntimeError`` on purpose, following ``DataRootError``: callers wrap
    filesystem work in ``except OSError``, and an ``OSError`` subclass here
    would be swallowed by a handler written for a missing file, restoring the
    silence this seam exists to remove.
    """


class ManifestMissing(ManifestError):
    """No manifest at the path asked for, or at any default path."""


class NoManifestOnThisTree(ManifestMissing):
    """The default search found no manifest anywhere under this data root.

    A SUBCLASS, raised at exactly one site, because two refusals that read the
    same are not the same. A manifest NAMED (through ``HEADING_OS_2_MANIFEST``
    or an explicit ``manifest=``) and not there is a caller pointing at the
    wrong side of a migration, and stays plain `ManifestMissing`. A tree with no
    manifest at all has not entered the migration: a public clone, a service
    host's pull-only copy. On such a
    tree the legacy directories are the truth by definition, and
    `scripts/heading_os_2/compat.py` is allowed to answer from them for THIS
    exception and no other. Nothing in this module falls back; see there.
    """


class ManifestMalformed(ManifestError):
    """A manifest that exists but cannot be trusted to answer."""


class UnknownKind(ManifestError):
    """The family/leaf pair asked for has no answer in this vocabulary or file."""


class AmbiguousLocation(ManifestError):
    """A single-directory answer was asked for where there is no single directory."""


@dataclass(frozen=True)
class LocationRow:
    """One family/leaf pair: where its records are today, and where they go."""

    family: str
    leaf: str
    current_dir: str
    target_dir: str
    state: str
    files: int
    spread_over_dirs: int

    @property
    def kind(self) -> str:
        """`family/leaf`, the spelling used in messages and log lines."""
        return f"{self.family}/{self.leaf}"

    @property
    def has_common_root(self) -> bool:
        """True when one directory contains every record of this pair."""
        return self.current_dir != NO_COMMON_ROOT

    @property
    def has_evidenced_home(self) -> bool:
        """True when the records agree on one directory, and there are enough of
        them for that agreement to mean anything."""
        return (self.spread_over_dirs == 1
                and self.files >= _HOME_EVIDENCE_MIN_FILES)


@dataclass(frozen=True)
class FileSet:
    """The files of one kind, WITH the date the snapshot that named them was taken.

    A list of paths on its own invites being read as the truth about the tree.
    It is not: it is what the per-file table said when it was generated, so a
    record created since is absent and a record deleted since is still listed.
    Carrying `generated` beside the paths is what lets a caller weigh that
    instead of assuming it away. Iterates over the paths, so a caller that only
    wants them writes `for p in read_files(...)` and nothing is in its way.
    """

    kind: str
    files: tuple[Path, ...]
    generated: str | None

    def __iter__(self):
        return iter(self.files)

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, index):
        return self.files[index]


@dataclass(frozen=True)
class ReadScope:
    """Everything a caller needs to read a kind honestly during the transition."""

    row: LocationRow
    dirs: tuple[Path, ...]
    #: True when everything under `dirs` belongs to this kind and nothing else
    #: does. False means the caller must filter: a directory that holds this
    #: kind may hold others too.
    exclusive: bool
    #: How many files of this kind's FAMILY have no leaf decided yet. Any of
    #: them could belong to this leaf, so a non-zero value means this read is
    #: incomplete by up to that many records. Zero after the leaves are settled.
    undecided_in_family: int = 0
    #: How many files have no FAMILY decided yet. Any of them could belong to
    #: this kind too. Carried separately because the two shrink by different
    #: work: this one by classifying a file at all, the one above by choosing
    #: between the leaves of a family already settled.
    undecided_family_unknown: int = 0
    #: The date the generator's report CLAIMS the tables were written, or None
    #: when it does not say. Reported so a caller can judge how old this answer
    #: is; nothing here expires on it. See `manifest_generated`.
    generated: str | None = None

    @property
    def kind(self) -> str:
        return self.row.kind

    @property
    def complete(self) -> bool:
        """True when no record anywhere could still turn out to be this kind.

        Both counts, not just the family's own: a file with no family at all
        could be classified into this leaf tomorrow. During phase 0 this is
        False for every kind, and that is the honest answer rather than a
        defect in the flag.
        """
        return (self.undecided_in_family == 0
                and self.undecided_family_unknown == 0)


