def _reject(path: Path, lineno: int | None, problem: str) -> ManifestMalformed:
    where = f"{path}:{lineno}" if lineno is not None else str(path)
    return ManifestMalformed(f"{where}: {problem}")


def _check_relative(value: str, column: str, path: Path, lineno: int) -> str:
    """A manifest directory must be relative, inside the tree, POSIX-spelled."""
    if not value:
        raise _reject(path, lineno, f"{column} is empty")
    if "\\" in value:
        raise _reject(path, lineno, f"{column}={value!r} uses a backslash; "
                                    f"manifest paths are POSIX-spelled")
    if value.startswith("/") or (len(value) > 1 and value[1] == ":"):
        raise _reject(path, lineno, f"{column}={value!r} is absolute; manifest "
                                    f"paths are relative to the data root")
    if ".." in PurePosixPath(value).parts:
        raise _reject(path, lineno, f"{column}={value!r} climbs out of the data root")
    stripped = value.strip("/")
    return stripped or NO_COMMON_ROOT


def _check_count(value: str, column: str, path: Path, lineno: int) -> int:
    try:
        n = int(value)
    except ValueError:
        raise _reject(path, lineno,
                      f"{column}={value!r} is not a whole number") from None
    if n < 0:
        raise _reject(path, lineno, f"{column}={value!r} is negative")
    return n


def _header_or_reject(cells: list[str], expected: tuple[str, ...],
                      path: Path, lineno: int) -> None:
    if tuple(cells) != expected:
        raise _reject(
            path, lineno,
            f"header is {cells!r}, expected {list(expected)!r}. Columns are "
            f"read by NAME and never positionally: two of them are plausible "
            f"paths, so a swapped pair would resolve every caller to the wrong "
            f"side of the migration without a word.",
        )


def _parse_locations(text: str, path: Path) -> dict[tuple[str, str], LocationRow]:
    rows: dict[tuple[str, str], LocationRow] = {}
    header_seen = False
    for lineno, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith(COMMENT_PREFIX):
            continue
        cells = [c.strip() for c in raw.split("\t")]
        if not header_seen:
            _header_or_reject(cells, LOCATION_COLUMNS, path, lineno)
            header_seen = True
            continue
        if len(cells) != len(LOCATION_COLUMNS):
            raise _reject(path, lineno,
                          f"{len(cells)} tab-separated fields, expected "
                          f"{len(LOCATION_COLUMNS)}")
        family, leaf, current_dir, target_dir, state, files, spread = cells
        if not is_valid(family, leaf):
            what = "family" if family not in FAMILIES else f"leaf of {family}"
            known = (", ".join(sorted(FAMILIES)) if family not in FAMILIES
                     else ", ".join(FAMILIES[family]))
            raise _reject(path, lineno,
                          f"{family}/{leaf} is not a pair this vocabulary "
                          f"defines (unknown {what}; known: {known})")
        if state not in STATES:
            raise _reject(path, lineno,
                          f"state={state!r} is not one of {list(STATES)!r}")
        current_dir = _check_relative(current_dir, "current_dir", path, lineno)
        target_dir = _check_relative(target_dir, "target_dir", path, lineno)
        if target_dir == NO_COMMON_ROOT:
            raise _reject(path, lineno,
                          f"{family}/{leaf} has no target_dir. Every kind has a "
                          f"destination even when it has no home today; the "
                          f"data root itself is not one.")
        n_files = _check_count(files, "files", path, lineno)
        n_spread = _check_count(spread, "spread_over_dirs", path, lineno)
        # Both shape checks below are `moved` and nothing else, deliberately.
        # A `not-for-migration` row keeps a `current_dir` that differs from its
        # target and a spread greater than one, because that is what it MEANS:
        # records at both addresses, permanently. Widening either check to
        # "finished" would refuse every row this state exists to describe.
        if state == STATE_MOVED and current_dir != target_dir:
            raise _reject(
                path, lineno,
                f"{family}/{leaf} is marked 'moved' but current_dir "
                f"({current_dir!r}) and target_dir ({target_dir!r}) disagree. "
                f"That is the shape a half-finished flip leaves behind: the "
                f"state says the records are at the target and the path still "
                f"points at the source. Refusing rather than picking one.",
            )
        if state == STATE_MOVED and n_spread > 1:
            raise _reject(
                path, lineno,
                f"{family}/{leaf} is marked 'moved' but still claims "
                f"spread_over_dirs={n_spread}. A moved kind lives in exactly "
                f"one directory; regenerate the row rather than editing the "
                f"state by hand.",
            )
        if n_files and not n_spread:
            raise _reject(path, lineno,
                          f"{family}/{leaf} has {n_files} files across 0 "
                          f"directories")
        key = (family, leaf)
        if key in rows:
            raise _reject(path, lineno,
                          f"{family}/{leaf} appears twice; a second row would "
                          f"silently win or lose on read order")
        rows[key] = LocationRow(family, leaf, current_dir, target_dir, state,
                                n_files, n_spread)
    if not header_seen:
        raise _reject(path, None, "no header row; the file is empty or all comments")
    if not rows:
        raise _reject(path, None,
                      "header but no rows. That is what a truncated write "
                      "leaves behind, and it would refuse every lookup one at a "
                      "time instead of saying so once.")
    return rows


@dataclass(frozen=True)
class PerFileIndex:
    """The per-file table, indexed by kind.

    THREE counts, not one, because a row can fail to be indexed in three
    different ways and a caller reads them differently. Collapsing them into one
    "unclassified" number is how 543 records awaiting a decision get reported
    beside 397 caches as if they were the same thing. MEASURED 2026-09-13 on the
    real manifest, and each number is a different kind of debt:

    `out_of_scheme` (410) -- no family, no leaf, method `skip`, `unmatched` or
    `unresolved`. Out of the scheme by decision: caches, temporaries, sync
    bookkeeping. Nothing will ever read one as a record.

    `undecided_family` (543) -- no family, no leaf, method `judgement`. A real
    record that nobody has classified yet. Any of them could belong to ANY kind,
    so every read during phase 0 is incomplete by up to this many.

    `undecided_by_family` (44: 24 `canon`, 20 `status`, which that manifest still
    spells `state`) -- family settled, leaf
    not, method `judgement`. What `families.py` produces where a rule fixes the
    family and the leaf needs a human to read the file. A read of any leaf of
    that family is incomplete by up to that family's count.

    All three travel to the caller. The second and third travel on every
    `ReadScope`, because a complete-LOOKING answer that quietly omits them is
    the failure this module exists to prevent, one level up from the paths.
    """

    dirs_by_kind: MappingProxyType
    files_by_kind: MappingProxyType
    #: kind -> the `target` this table itself claims for it. Kept so the two
    #: generated tables can be held against each other; see `check_agreement`.
    targets_by_kind: MappingProxyType
    undecided_by_family: MappingProxyType
    undecided_family: int
    out_of_scheme: int
    total: int


def _parse_per_file(text: str, path: Path) -> PerFileIndex:
    dirs: dict[tuple[str, str], list[str]] = {}
    files: dict[tuple[str, str], list[str]] = {}
    seen: dict[tuple[str, str], set[str]] = {}
    undecided: dict[str, int] = {}
    targets: dict[tuple[str, str], str] = {}
    undecided_family = 0
    out_of_scheme = 0
    total = 0
    header_seen = False
    for lineno, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith(COMMENT_PREFIX):
            continue
        cells = [c.strip() for c in raw.split("\t")]
        if not header_seen:
            _header_or_reject(cells, PER_FILE_COLUMNS, path, lineno)
            header_seen = True
            continue
        if len(cells) != len(PER_FILE_COLUMNS):
            raise _reject(path, lineno,
                          f"{len(cells)} tab-separated fields, expected "
                          f"{len(PER_FILE_COLUMNS)}")
        rel_path, family, leaf, method = cells[0], cells[1], cells[2], cells[3]
        total += 1
        if not family and not leaf:
            # Two very different debts wearing the same empty cells, told apart
            # by the METHOD column rather than by guesswork. A cache is out of
            # the scheme forever; a record awaiting judgement is one decision
            # away from being in it, and the second number is the one that has
            # to shrink.
            if method == JUDGEMENT_METHOD:
                undecided_family += 1
            elif method in OUT_OF_SCHEME_METHODS:
                out_of_scheme += 1
            else:
                raise _reject(
                    path, lineno,
                    f"no family and no leaf, with method {method!r}. Only "
                    f"{JUDGEMENT_METHOD!r} (awaiting a decision) and "
                    f"{list(OUT_OF_SCHEME_METHODS)!r} (out of the scheme) may "
                    f"leave both empty; anything else is a generator defect "
                    f"that would drop a classified record silently.")
            continue
        if family and not leaf:
            # The family is settled and the leaf is not: a `judgement` row whose
            # second pass has not run. It cannot be indexed under a kind, but it
            # is a real record of a real family, so a read of any leaf of that
            # family is incomplete by one more file and must be able to say so.
            if family not in FAMILIES:
                raise _reject(path, lineno,
                              f"{family!r} is not a HEADING OS 2 family")
            undecided[family] = undecided.get(family, 0) + 1
            continue
        if not family and leaf:
            raise _reject(path, lineno,
                          f"leaf {leaf!r} with no family. A leaf name is only "
                          f"meaningful inside a family, and several families "
                          f"could claim this one.")
        if not is_valid(family, leaf):
            raise _reject(path, lineno,
                          f"{family!r}/{leaf!r} is not a pair this vocabulary "
                          f"defines")
        rel_path = _check_relative(rel_path, "path", path, lineno)
        key = (family, leaf)
        target = cells[5]
        if not target:
            raise _reject(path, lineno,
                          f"{family}/{leaf} has no target. A row that carries a "
                          f"kind carries the destination that kind goes to; an "
                          f"empty one here is what a partial classification "
                          f"leaves behind.")
        target = _check_relative(target, "target", path, lineno)
        if targets.setdefault(key, target) != target:
            raise _reject(path, lineno,
                          f"{family}/{leaf} is sent to {target!r} here and to "
                          f"{targets[key]!r} on an earlier row. One kind has one "
                          f"destination; two of them would split the records of "
                          f"a single kind across two directories at the move.")
        files.setdefault(key, []).append(rel_path)
        parent = str(PurePosixPath(rel_path).parent)
        bucket = seen.setdefault(key, set())
        if parent not in bucket:
            bucket.add(parent)
            dirs.setdefault(key, []).append(parent)
    if not header_seen:
        raise _reject(path, None, "no header row; the file is empty or all comments")
    return PerFileIndex(
        dirs_by_kind=MappingProxyType({k: tuple(sorted(v)) for k, v in dirs.items()}),
        files_by_kind=MappingProxyType({k: tuple(sorted(v)) for k, v in files.items()}),
        targets_by_kind=MappingProxyType(dict(targets)),
        undecided_by_family=MappingProxyType(dict(undecided)),
        undecided_family=undecided_family,
        out_of_scheme=out_of_scheme,
        total=total,
    )


@functools.lru_cache(maxsize=4)
def _parse_locations_cached(path_str: str, mtime_ns: int, size: int):
    """Parse one per-family table. Keyed on file IDENTITY, never bare.

    See the module docstring for why the key carries mtime: a bare cache's stale
    window spans a migration step.

    `lru_cache` does not memoise exceptions, so a malformed manifest is
    re-parsed, and re-refused, on every call rather than frozen into the cache.
    Fixing the file in place is enough to recover: no restart, no
    `invalidate_cache()`.
    """
    path = Path(path_str)
    return MappingProxyType(_parse_locations(_read_text(path), path))


@functools.lru_cache(maxsize=2)
def _parse_per_file_cached(path_str: str, mtime_ns: int, size: int) -> PerFileIndex:
    """Parse one per-file table. Same identity key, same reasons.

    `maxsize=2` rather than 4: this one is 1.4 MB and 11,803 rows, and holding
    four parsed copies of it buys nothing a single workspace can use.
    """
    path = Path(path_str)
    return _parse_per_file(_read_text(path), path)


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        # Not an OSError, and so not caught by the handler around `stat`.
        # `load_routing_map` was bitten by exactly this shape on 2026-08-30.
        raise _reject(path, None, f"is not valid UTF-8 ({exc})") from exc


def _stat_or_refuse(path: Path, what: str) -> os.stat_result:
    try:
        return path.stat()
    except OSError as exc:
        raise ManifestMissing(
            f"Cannot read the {what} at {path}: {exc}. Refusing to fall back to "
            f"a guessed directory."
        ) from exc


def invalidate_cache() -> None:
    """Drop every parsed table. For a caller that needs certainty over speed."""
    _parse_locations_cached.cache_clear()
    _parse_per_file_cached.cache_clear()


def load_locations(manifest: Path | None = None,
                   data_root: Path | None = None
                   ) -> dict[tuple[str, str], LocationRow]:
    """Every row of the per-family table, keyed by (family, leaf).

    A fresh dict per call, so a caller mutating it cannot corrupt the shared
    cached mapping for the rest of the process. The rows themselves are frozen.
    """
    path = _resolve_dir(manifest, data_root) / LOCATIONS_FILENAME
    st = _stat_or_refuse(path, "family manifest")
    return dict(_parse_locations_cached(str(path), st.st_mtime_ns, st.st_size))


def load_per_file(manifest: Path | None = None,
                  data_root: Path | None = None) -> PerFileIndex:
    """The per-file table, indexed by kind."""
    path = _resolve_dir(manifest, data_root) / PER_FILE_FILENAME
    st = _stat_or_refuse(path, "per-file manifest")
    return _parse_per_file_cached(str(path), st.st_mtime_ns, st.st_size)


def manifest_generated(manifest: Path | None = None,
                       data_root: Path | None = None) -> str | None:
    """The date the generator's own report CLAIMS the tables were written, or None.

    Reported, never enforced. There is no expiry here, nothing refuses on age,
    and nothing stats the tree to check: a visible age a caller can judge is
    worth more than a threshold somebody picked. Operator ruling relayed by HELM,
    2026-09-13.

    Absent, unreadable or malformed report -> None, meaning unknown. A missing
    report is not a reason to refuse an answer the two tables can give.
    """
    import json

    path = _resolve_dir(manifest, data_root) / REPORT_FILENAME
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return None
    if not isinstance(data, dict):
        return None
    value = data.get("generated")
    return value if isinstance(value, str) and value else None


def check_agreement(manifest: Path | None = None,
                    data_root: Path | None = None) -> None:
    """Hold the two generated tables against each other, and refuse on a split.

    Both are written from one pass over one tree, so they cannot disagree while
    the generator is right. That is exactly why the check is worth having: the
    day they disagree, the generator is wrong, and the disagreement is otherwise
    invisible -- each table reads perfectly well on its own.

    Two ways they can split, and both refuse rather than warn:

      * a kind whose `target` in the per-file table is not the `target_dir` in
        the per-family table. A caller reading one and a mover reading the other
        would send records and readers to different directories.
      * a kind the per-file table places and the per-family table does not. The
        records exist and nothing says where they are going.

    A warning would be the wrong instrument. Nobody reads a warning inside a
    daemon, and "nothing would notice" is the property this seam exists to
    remove.
    """
    rows = load_locations(manifest, data_root)
    index = load_per_file(manifest, data_root)
    where = _resolve_dir(manifest, data_root)
    for kind, target in sorted(index.targets_by_kind.items()):
        row = rows.get(kind)
        if row is None:
            raise ManifestMalformed(
                f"{kind[0]}/{kind[1]} is placed by {PER_FILE_FILENAME} and has "
                f"no row in {LOCATIONS_FILENAME} (both under {where}). The "
                f"records exist and nothing says where they are going."
            )
        if row.target_dir != target:
            raise ManifestMalformed(
                f"{row.kind}: {PER_FILE_FILENAME} sends it to {target!r} and "
                f"{LOCATIONS_FILENAME} to {row.target_dir!r} (both under "
                f"{where}). Two generated tables from one pass over one tree "
                f"cannot disagree while the generator is right; regenerate both "
                f"rather than editing either."
            )


