def _env_manifest_dir() -> Path | None:
    """The ``HEADING_OS_2_MANIFEST`` override, or None when it is unset.

    Set-but-missing raises. Unset returns None, the ordinary path for every
    caller that does not use the override.
    """
    raw = os.environ.get(MANIFEST_ENV)
    if not raw:
        return None
    cand = Path(raw).expanduser()
    if cand.is_file():
        return cand.parent.resolve()
    if cand.is_dir() and (cand / LOCATIONS_FILENAME).is_file():
        return cand.resolve()
    raise ManifestMissing(
        f"{MANIFEST_ENV} is set to {raw!r}, which is neither a "
        f"{LOCATIONS_FILENAME} nor a directory containing one. Refusing to fall "
        f"back to a default: naming a manifest explicitly and silently getting "
        f"another is how a caller resolves against the wrong side of a "
        f"migration. Point it at the file or its directory, or unset it."
    )


def candidate_manifest_dirs(data_root: Path | None = None) -> list[Path]:
    """Every directory the default search would consider, in order.

    Exposed because the refusal message names them, and a refusal that says
    where it looked is the difference between a five-second fix and a hunt.

    The phase-0 candidate is the registry name `ho2-migration-workdir`, the
    migration's own working directory, and the name must stay a `path:` entry.
    `data_path()` resolves a `record:` name by calling `write_dir`, which calls
    `row_for`, which calls `load_locations`, which calls `_resolve_dir`, which
    calls `manifest_dir`, which calls THIS function, so a `record:` name here
    would re-enter the resolver mid-resolution. A `path:` name reaches only the
    registry file and the data root. MEASURED 2026-09-22 and recorded in the
    since-deleted `get_outputs_dir` notes: wiring the old bare helper to the
    vacated-home guard drove `candidate_manifest_dirs(None)` 13 frames deep
    before an artificial cap, with the guard swallowing the `RecursionError`
    into a silent permit. Every record address in the workspace flows through
    here, so that failure would be total and quiet.

    Until 2026-09-25 this candidate was `get_outputs_dir()` joined to the dated
    constant. HOS-5 section 6 deleted that wrapper on the operator's word, "old
    way should go out and do not stay in the workspace". A tree whose registry
    does not name the directory, a public clone for one, has
    no phase-0 candidate at all rather than an invented one; the permanent
    candidate is still searched first and the refusal still names it.

    It is also a FALLBACK and not the usual answer. MEASURED 2026-09-22 on the
    operator's overlay: both candidates carry `family-locations.tsv`, and
    `manifest_dir` returns the permanent one because it is first in the list.
    """
    global _PHASE0_UNNAMED
    base = Path(data_root) if data_root is not None else get_data_root()
    permanent = base / PERMANENT_MANIFEST_DIR
    # Lazily, because `scripts.utils.data_path` imports this module. The
    # handler sits here at the call rather than in a helper: a tree that does
    # not name the working directory simply has one candidate fewer. An
    # explicit `data_root` asks that tree's own registry, so the directory
    # moves with its registry line on every tree; until 2026-09-25 that branch
    # joined the dated pre-reform address to `outputs/` instead, and would have
    # gone on answering the old address after the move.
    from scripts.utils.data_path import DataPathError, data_path
    try:
        phase0 = data_path("ho2-migration-workdir", data_root=data_root)
    except DataPathError as exc:
        _PHASE0_UNNAMED = (f"no phase-0 candidate: the registry does not "
                           f"answer 'ho2-migration-workdir' "
                           f"({type(exc).__name__})")
        return [permanent]
    _PHASE0_UNNAMED = None
    return [permanent, phase0]


def manifest_dir(data_root: Path | None = None) -> Path:
    """The manifest directory this workspace reads, or a refusal naming the tries."""
    env = _env_manifest_dir()
    if env is not None:
        return env
    candidates = candidate_manifest_dirs(data_root)
    for cand in candidates:
        if (cand / LOCATIONS_FILENAME).is_file():
            return cand.resolve()
    tried = "\n  ".join(str(c / LOCATIONS_FILENAME) for c in candidates)
    if _PHASE0_UNNAMED:
        tried += "\n  (" + _PHASE0_UNNAMED + ")"
    raise NoManifestOnThisTree(
        "No HEADING OS 2 family manifest found. Looked at:\n  " + tried + "\n"
        f"Set {MANIFEST_ENV} to point at one, or generate it with "
        f"scripts/heading_os_2/manifest.py. Refusing to guess a directory: a "
        f"resolver that answers without the manifest is the failure this seam "
        f"was built to prevent."
    )


def _resolve_dir(manifest: Path | None,
                 data_root: Path | None) -> Path:
    if manifest is not None:
        cand = Path(manifest)
        return cand.parent if cand.is_file() else cand
    return manifest_dir(data_root)


