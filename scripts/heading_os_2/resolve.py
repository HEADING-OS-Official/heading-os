def row_for(family: str, leaf: str, *,
            manifest: Path | None = None,
            data_root: Path | None = None) -> LocationRow:
    """The manifest row for one kind, or a refusal that says which kind of no.

    The two failures are kept apart on purpose. "This vocabulary has no such
    leaf" is a typo in the caller; "the vocabulary has it, the manifest does
    not" is a missing row in a generated file. One message for both sends the
    reader to the wrong file.
    """
    if not is_valid(family, leaf):
        if family not in FAMILIES:
            raise UnknownKind(
                f"{family!r} is not a HEADING OS 2 family. The nine are: "
                f"{', '.join(sorted(FAMILIES))}."
            )
        raise UnknownKind(
            f"{leaf!r} is not a leaf of {family!r}. Its leaves are: "
            f"{', '.join(FAMILIES[family])}."
        )
    rows = load_locations(manifest, data_root)
    try:
        return rows[(family, leaf)]
    except KeyError:
        where = _resolve_dir(manifest, data_root) / LOCATIONS_FILENAME
        raise UnknownKind(
            f"{family}/{leaf} is a valid kind but has no row in {where}. The "
            f"vocabulary defines it and the manifest does not place it, so "
            f"nothing here knows where those records are. Add the row."
        ) from None


def _data_root(data_root: Path | None) -> Path:
    return (Path(data_root) if data_root is not None else get_data_root()).resolve()


def _under(base: Path, rel: str, kind: str) -> Path:
    """`base / rel`, resolved, with containment checked AFTER resolution.

    After, so that a symlinked component cannot carry a row out of the tree that
    the textual check in `_check_relative` already cleared.
    """
    resolved = (base / rel).resolve() if rel != NO_COMMON_ROOT else base
    if resolved != base and base not in resolved.parents:
        raise ManifestMalformed(
            f"{kind}: {rel!r} resolves to {resolved}, which is outside the data "
            f"root {base}."
        )
    return resolved


def write_dir(family: str, leaf: str, *,
              manifest: Path | None = None,
              data_root: Path | None = None) -> Path:
    """The one directory a NEW record of this kind belongs in, today.

    Always defined, for every kind, on both sides of the move. It does not
    create the directory.

    The rule, and it is narrower than it first looks. A new record joins the
    existing ones ONLY where the existing ones agree on a directory and there
    are enough of them for that agreement to be evidence (`has_evidenced_home`,
    which is 7 of the measured 33 pairs). Everywhere else it goes straight to
    `target_dir` -- the new scheme, from day one -- because a new record has no
    reason to join a mess it can avoid.

    Why not "current_dir unless the pair is spread", which is the obvious rule:
    `current_dir` is the deepest COMMON directory, and for a pair whose records
    sit in two sibling legacy homes that is their shared parent, which is
    nobody's home. Measured on the 2026-09-12 manifest, that rule sends a new
    `work/draft` and a new `asset/bundle` to `outputs/` itself, a new (leak-guard: ok, history)
    `status/entity` to `crm/` rather than `crm/contacts/`, and a new `asset/media`  # leak-guard: ok (history: measured on the 2026-09-12 manifest)
    into one dated transcript directory that happens to hold the only existing
    file of its kind. Each of those is a plausible-looking wrong answer, which is
    the one output this module may not produce.
    """
    row = row_for(family, leaf, manifest=manifest,
                  data_root=data_root)
    base = _data_root(data_root)
    # `moved` and nothing else on the left: a `not-for-migration` kind takes the
    # same branch as `moving`, so the destination of a NEW record is decided by
    # the evidence its existing records give, exactly as it was the day before
    # the state changed. Its records outside the target are there by decision,
    # not by accident, and that says nothing about where the next one belongs.
    if row.state == STATE_MOVED or not row.has_evidenced_home:
        return _under(base, row.target_dir, row.kind)
    return _under(base, row.current_dir, row.kind)


def read_scope(family: str, leaf: str, *,
               manifest: Path | None = None,
               data_root: Path | None = None) -> ReadScope:
    """Every directory a reader of this kind must look in, and whether it is clean.

    `dirs` is exact, and it can be long: 216 entries for the widest measured
    pair. Callers must not assume one. The rules, in order:

      * `moved` -- one directory, the target. The per-file table is NOT read;
        its paths describe the tree before the move and are stale by
        construction.
      * otherwise -- every distinct directory the per-file table places this
        kind in, PLUS `write_dir()` when that is not already among them, so that
        a record written through this seam is always found by a read through it,
        before, during and after the move.
      * `moving`, `not-for-migration` -- additionally the target, because both
        put records on both sides at once: the first while a copy is under way,
        the second permanently, because the operator ruled the rest of them
        STAYS. The two are one question here (`reads_both_homes`) and are asked
        as one, so the day a third state joins them nothing has to be found
        twice. A check pinned the five real kinds, the same directory set under
        either value and to the entry; it was parked in the 2026-09-21
        test-suite split, so `reads_both_homes` is now held by this docstring
        and by whoever adds the third state.

    `exclusive` says whether everything under `dirs` belongs to this kind.
    It is True only for a `moved` kind, whose target directory holds that kind
    and nothing else. During the transition a legacy directory holds several
    kinds at once, so a caller that globs `dirs` must filter, and this flag is
    how it learns that without having to know the migration's shape.

    `undecided_in_family` is the other half of the same honesty. A `judgement`
    row whose leaf has not been settled carries a family and no leaf, so it is
    in no kind's index at all; any of those files could belong to THIS leaf.
    Reporting the count is what stops a complete-looking read from being trusted
    as one.
    """
    row = row_for(family, leaf, manifest=manifest,
                  data_root=data_root)
    base = _data_root(data_root)
    if row.state == STATE_MOVED:
        return ReadScope(row=row,
                         dirs=(_under(base, row.target_dir, row.kind),),
                         exclusive=True,
                         generated=manifest_generated(manifest, data_root))
    check_agreement(manifest, data_root)
    index = load_per_file(manifest, data_root)
    undecided = index.undecided_by_family.get(row.family, 0)
    undecided_family_unknown = index.undecided_family
    rels = list(index.dirs_by_kind.get((row.family, row.leaf), ()))
    write_rel = (row.current_dir if row.has_evidenced_home else row.target_dir)
    if write_rel not in rels:
        rels.append(write_rel)
    if reads_both_homes(row.state) and row.target_dir not in rels:
        rels.append(row.target_dir)
    dirs = tuple(_under(base, rel, row.kind) for rel in sorted(set(rels)))
    return ReadScope(row=row, dirs=dirs, exclusive=False,
                     undecided_in_family=undecided,
                     undecided_family_unknown=undecided_family_unknown,
                     generated=manifest_generated(manifest, data_root))


def read_dirs(family: str, leaf: str, *,
              manifest: Path | None = None,
              data_root: Path | None = None) -> list[Path]:
    """Every directory holding records of this kind. Many, and never assume one."""
    return list(read_scope(family, leaf, manifest=manifest,
                           data_root=data_root).dirs)


def read_files(family: str, leaf: str, *,
               manifest: Path | None = None,
               data_root: Path | None = None) -> FileSet:
    """Every FILE the per-file table places in this kind, as of the last generation.

    The exact answer, and the only one that is exact during the transition: a
    directory holding this kind holds others too. It is a snapshot, so a record
    created since the table was generated is not in it -- use it to find what
    exists, not to prove what does not. The returned `FileSet` carries the date
    of that snapshot beside the paths, because a bare list of paths invites
    being read as the truth about the tree.

    Refuses for a `moved` kind: after the move the directory IS the answer and
    the table's paths are stale by construction.
    """
    row = row_for(family, leaf, manifest=manifest,
                  data_root=data_root)
    if row.state == STATE_MOVED:
        raise AmbiguousLocation(
            f"{row.kind} is 'moved'; the per-file table describes the tree "
            f"before the move and its paths for this kind are stale. Read "
            f"{row.target_dir} instead."
        )
    base = _data_root(data_root)
    check_agreement(manifest, data_root)
    index = load_per_file(manifest, data_root)
    rels = index.files_by_kind.get((row.family, row.leaf), ())
    return FileSet(kind=row.kind,
                   files=tuple(_under(base, rel, row.kind) for rel in rels),
                   generated=manifest_generated(manifest, data_root))


def read_records(family: str, leaf: str, *,
                 suffixes: tuple[str, ...] | None = None,
                 manifest: Path | None = None,
                 data_root: Path | None = None) -> FileSet:
    """Every record of this kind that is ON DISK now, on either side of the move.

    The reader a converted caller wants. `read_files()` is exact before the move
    and refuses after it; `read_dirs()` answers after the move and hands back
    directories that hold other kinds too before it. A caller that has to pick
    between them by state has been handed the migration's shape, which is the
    thing the seam exists to keep out of callers. This function makes the
    choice and returns files in both states:

      * `not-moved`, `moving`, `not-for-migration` -- the per-file table's paths for this kind that
        exist on disk, PLUS every file under `write_dir()` for it, because a
        record written through this seam since the table was generated is not
        in the table and must still be found by a read through it. A table
        path that no longer exists is dropped: it was deleted since the
        snapshot, and a reader that reports a file it cannot open is reporting
        the table, not the tree.
      * `moved` -- every file under the target directory. The table is stale by
        construction and is not consulted.

    `suffixes` narrows to file extensions (`(".md",)`); None returns every
    regular file. Directories, and the family README that sits at a family
    ROOT, are never records. The returned `FileSet` carries `generated` so a
    caller can still say how old the snapshot half of the answer is.

    A caller that wants one SUB-LOCATION of a kind (the `/council` transcripts
    inside `trace/scratch`) filters on a path component, which survives the
    move because the move keeps the source subpath under the target.
    """
    row = row_for(family, leaf, manifest=manifest, data_root=data_root)
    base = _data_root(data_root)
    generated = manifest_generated(manifest, data_root)

    def _wanted(path: Path) -> bool:
        # A symlink is never a record: `is_file()` follows it, and a link
        # planted under a target directory would read a file outside the
        # tree as one of this kind (outside review 2026-09-14, Astra a2 #8).
        if path.is_symlink() or not path.is_file():
            return False
        return suffixes is None or path.suffix in suffixes

    def _walk(directory: Path):
        if not directory.is_dir():
            return
        for path in sorted(directory.rglob("*")):
            if _wanted(path):
                yield path

    if row.state == STATE_MOVED:
        target = _under(base, row.target_dir, row.kind)
        return FileSet(kind=row.kind, files=tuple(_walk(target)), generated=generated)

    check_agreement(manifest, data_root)
    index = load_per_file(manifest, data_root)
    found: dict[Path, None] = {}
    mine = index.files_by_kind.get((row.family, row.leaf), ())
    for rel in mine:
        path = _under(base, rel, row.kind)
        if _wanted(path):
            found[path] = None
    # Files the table places in ANOTHER kind. A legacy write home is shared
    # by construction (two kinds whose records each sit in one directory can
    # sit in the same one), so a walk of it must not adopt the neighbour's
    # records (Astra a2 #5).
    others: set[Path] = set()
    for kind, rels in index.files_by_kind.items():
        if kind != (row.family, row.leaf):
            for rel in rels:
                others.add(_under(base, rel, kind[0] + "/" + kind[1]))
    for path in _walk(write_dir(family, leaf, manifest=manifest, data_root=data_root)):
        if path not in others:
            found[path] = None
    # The target directory holds this kind and nothing else, on both sides:
    # a record written there through the seam, or carried there by a move
    # that stopped before the flip (Astra a2 #6), is a record of this kind
    # whatever the row's state says.
    for path in _walk(_under(base, row.target_dir, row.kind)):
        found[path] = None
    return FileSet(kind=row.kind, files=tuple(sorted(found)), generated=generated)


def read_root(family: str, leaf: str, *,
              manifest: Path | None = None,
              data_root: Path | None = None) -> Path:
    """The ONE directory holding this kind, or a refusal.

    Refuses whenever `spread_over_dirs` is greater than one. Deliberately
    stricter than it strictly has to be: `current_dir` is a common ancestor, so
    a RECURSIVE read of it would in fact reach every record of a spread pair.
    But this function's name promises one directory, its callers will glob it,
    and the failure it replaces is specific -- on 2026-09-12 a plurality vote
    over `trace/scratch` returned one directory out of 216, and it looked
    exactly right. A caller that genuinely wants the common ancestor asks
    `read_scope()` and reads `row.current_dir` with `exclusive=False` in front
    of it, which is a sentence nobody writes by accident.
    """
    row = row_for(family, leaf, manifest=manifest,
                  data_root=data_root)
    if row.spread_over_dirs > 1:
        raise AmbiguousLocation(
            f"{row.kind} has {row.files} records across "
            f"{row.spread_over_dirs} directories; there is no single directory "
            f"to return. Use read_dirs() (or read_files()) and handle all of "
            f"them. Returning the most populous one would look right and miss "
            f"most of what was asked for."
        )
    if not row.has_common_root:
        raise AmbiguousLocation(
            f"{row.kind} has no common directory; its records sit directly "
            f"under the data root's subtrees. Use read_dirs()."
        )
    base = _data_root(data_root)
    return _under(base, row.current_dir, row.kind)


def all_kinds() -> list[tuple[str, str]]:
    """Every family/leaf pair the vocabulary defines, in declaration order."""
    return [(family, leaf) for family, leaves in FAMILIES.items() for leaf in leaves]


def unplaced_kinds(manifest: Path | None = None,
                   data_root: Path | None = None) -> list[tuple[str, str]]:
    """Pairs the vocabulary defines that the manifest does not place.

    Not enforced at load time: 33 of the 45 pairs are in use and the rest have
    no records yet, so a partial table is the normal state and refusing to read
    it would block the work that fills it. A guard or a report asks this
    question; `load_locations` does not.
    """
    rows = load_locations(manifest, data_root)
    return [kind for kind in all_kinds() if kind not in rows]


