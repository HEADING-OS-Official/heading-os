def _cli(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        prog="heading-os-2-resolve",
        description="Resolve a HEADING OS 2 family/leaf to the directories its "
                    "records live in today. Writing has one answer; reading, "
                    "during the transition, usually has several.",
    )
    parser.add_argument("--manifest", type=Path, default=None,
                        help="manifest directory (default: the search order in "
                             "the module docstring)")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_write = sub.add_parser("write", help="the one directory a new record goes in")
    p_write.add_argument("family")
    p_write.add_argument("leaf")

    p_read = sub.add_parser("read", help="every directory holding this kind")
    p_read.add_argument("family")
    p_read.add_argument("leaf")
    p_read.add_argument("--files", action="store_true",
                        help="list the individual files, not their directories")

    sub.add_parser("where", help="print the manifest directory in use")
    sub.add_parser("list", help="print every row: kind, current, target, state")
    sub.add_parser("check", help="parse both tables and report what is unplaced")

    args = parser.parse_args(argv)
    md = args.manifest

    try:
        if args.cmd == "write":
            print(write_dir(args.family, args.leaf, manifest=md))
            return 0

        if args.cmd == "read":
            if args.files:
                fileset = read_files(args.family, args.leaf, manifest=md)
                for p in fileset:
                    print(p)
                print(f"# {len(fileset)} file(s), from a snapshot generated "
                      f"{fileset.generated or 'on a date the report does not give'}",
                      file=sys.stderr)
                return 0
            scope = read_scope(args.family, args.leaf, manifest=md)
            for p in scope.dirs:
                print(p)
            print(f"# {len(scope.dirs)} director"
                  f"{'y' if len(scope.dirs) == 1 else 'ies'}, "
                  f"exclusive={scope.exclusive}, state={scope.row.state}, "
                  f"{scope.undecided_in_family} file(s) of family "
                  f"'{scope.row.family}' still have no leaf, "
                  f"{scope.undecided_family_unknown} file(s) have no family, "
                  f"snapshot generated "
                  f"{scope.generated or '(no date in the report)'}",
                  file=sys.stderr)
            return 0

        if args.cmd == "where":
            print(md if md else manifest_dir())
            return 0

        if args.cmd == "list":
            rows = load_locations(md)
            width = max(len(r.kind) for r in rows.values())
            for kind in all_kinds():
                row = rows.get(kind)
                if row is None:
                    print(f"{kind[0] + '/' + kind[1]:<{width}}  (no row)")
                    continue
                print(f"{row.kind:<{width}}  {row.current_dir}  ->  "
                      f"{row.target_dir}  [{row.state}]  {row.files} files / "
                      f"{row.spread_over_dirs} dirs")
            return 0

        if args.cmd == "check":
            where = Path(md) if md else manifest_dir()
            rows = load_locations(md)
            unplaced = unplaced_kinds(md)
            moved = sum(1 for r in rows.values() if r.state == STATE_MOVED)
            closed = sum(1 for r in rows.values()
                         if r.state == STATE_NOT_FOR_MIGRATION)
            spread = sum(1 for r in rows.values() if r.spread_over_dirs > 1)
            print(f"manifest: {where}")
            # `not yet` is counted as what is LEFT, not as "everything that is
            # not moved". A `not-for-migration` kind is finished and reporting
            # it as outstanding would leave a number that can never reach zero.
            print(f"rows: {len(rows)} of {len(all_kinds())} kinds; "
                  f"{moved} moved, {closed} not for migration, "
                  f"{len(rows) - moved - closed} not yet; "
                  f"{spread} spread over more than one directory")
            try:
                index = load_per_file(md)
                print(f"per-file: {index.total} rows; "
                      f"{index.out_of_scheme} out of the scheme, "
                      f"{index.undecided_family} awaiting a family")
                if index.undecided_by_family:
                    total_undecided = sum(index.undecided_by_family.values())
                    per_family = ", ".join(
                        f"{fam} {n}" for fam, n
                        in sorted(index.undecided_by_family.items()))
                    print(f"leaf undecided: {total_undecided} file(s) "
                          f"({per_family}) -- reads of those families are "
                          f"incomplete until each is settled")
            except ManifestMissing as exc:
                print(f"per-file: MISSING ({exc})")
                return 1
            try:
                check_agreement(md)
                print("the two tables agree on every kind's target")
            except ManifestMalformed as exc:
                print(f"TABLES DISAGREE: {exc}")
                return 2
            print(f"generated: {manifest_generated(md) or 'not stated'}")
            if unplaced:
                print(f"kinds with no row ({len(unplaced)}):")
                for family, leaf in unplaced:
                    print(f"  {family}/{leaf}")
            return 0
    except ManifestError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 2

    return 2


if __name__ == "__main__":  # pragma: no cover - exercised through the entry script
    sys.exit(_cli())
