def main() -> int:
    require_main_clone(__file__)
    ap = argparse.ArgumentParser(description="Bootstrap a private HEADING OS data repository.")
    default_path = get_workspace_root().parent / ".heading-os-data"
    ap.add_argument("--path", default=str(default_path),
                    help="target directory for the data repo (default: ../.heading-os-data)")
    ap.add_argument("--repo-name", default=None,
                    help="GitHub repo name (default: the target directory name without a leading dot)")
    ap.add_argument("--owner", default=None,
                    help="GitHub owner/org (default: your authenticated gh account)")
    ap.add_argument("--public", action="store_true",
                    help="create a PUBLIC repo (default is private — almost never what you "
                         "want for data). The first push will then be REFUSED by the "
                         "remote-identity wall: only the engine may push to a public repo.")
    ap.add_argument("--no-remote", action="store_true",
                    help="local scaffold + git only; do not create a GitHub repo or push")
    ap.add_argument("--dry-run", action="store_true", help="show what would happen; make no changes")
    layout = ap.add_mutually_exclusive_group()
    layout.add_argument("--check-layout", action="store_true",
                        help="report what in the data repository's layout stops the push "
                             "checks; exit 1 when anything does, 0 when nothing does")
    layout.add_argument("--repair-layout", action="store_true",
                        help="rename a root README.md to ABOUT.md, create the missing thread "
                             "homes and commit only those changes; no remote is touched")
    args = ap.parse_args()

    # Resolved to absolute, because two different working directories consume
    # this value. `init-data.py` is spawned with `cwd=get_workspace_root()`, so
    # a relative `--path mydata` scaffolded the tree at `<workspace>/mydata`,
    # while the .gitignore/README writes and every git command below ran
    # against `<caller cwd>/mydata`. Running from anywhere but the engine root
    # produced an empty scaffold in one directory and a git repo with no data
    # tree in another, and then pushed the wrong one.
    target = Path(args.path).expanduser().resolve()

    # BEFORE anything is written, because the first thing `main()` does after
    # this is scaffold a whole data tree at `target`. There is no legitimate
    # call with an engine-internal target: the data overlay is a SIBLING of the
    # engine by construction (`--path` defaults to `../.heading-os-data`), and
    # the engine is code only. A target inside the clone means either a typo or
    # a caller whose "temp" directory is not where it thinks it is, which is
    # exactly how 2026-09-08 happened.
    #
    # `require_outside_engine_clone` rather than a check written here: it is the
    # workspace's existing answer to this question (five callers already), and a
    # second copy is the one that stops being fixed.
    try:
        require_outside_engine_clone(target, "--path")
    except DataRootError as exc:
        print(f"{RED}REFUSING:{RESET} {exc}")
        return 2

    if args.check_layout or args.repair_layout:
        if not _scaffolded(target):
            print(f"{target} is not a HEADING OS data repository yet; nothing to check.")
            return 2
        if args.repair_layout:
            return repair_layout(target, args.dry_run, commit=True)
        problems = layout_problems(target)
        for problem in problems:
            print(problem)
        return 1 if problems else 0

    repo_name = args.repo_name or target.name.lstrip(".")
    private = not args.public

    print(f"{BOLD}{CYAN}== Bootstrap private data repo =={RESET}")
    print(f"  target:  {target}")
    print(f"  repo:    {repo_name} ({'private' if private else 'PUBLIC'})")
    if args.no_remote:
        print(f"  remote:  {GRAY}skipped (--no-remote){RESET}")

    # Preconditions (skip the gh checks when not creating a remote).
    if not args.dry_run and not _have("git"):
        print(f"{RED}git is not installed.{RESET}")
        return 2
    if not args.no_remote and not args.dry_run:
        if not _have("gh"):
            print(f"{RED}GitHub CLI (gh) is not installed.{RESET} Install it, then `gh auth login`.")
            return 2
        if not _gh_authenticated():
            print(f"{RED}gh is not authenticated.{RESET} Run `gh auth login` first.")
            return 2

    if scaffold(target, args.dry_run) != 0:
        return 1
    if repair_layout(target, args.dry_run, commit=False) != 0:
        return 1
    write_repo_files(target, args.dry_run)
    if git_init_commit(target, args.dry_run) != 0:
        return 1

    if args.no_remote:
        if not args.dry_run:
            print(f"\n{YELLOW}Local repo ready (no remote).{RESET} "
                  f"Create one later with: {GRAY}gh repo create <name> --private --source {target} --remote origin --push{RESET}")
            print_wiring(target)
        return 0

    if create_remote(target, args.owner, repo_name, private, args.dry_run) != 0:
        return 1
    if not args.dry_run:
        if first_push(target) != 0:
            return 1
        print_wiring(target)
    else:
        print(f"{YELLOW}[dry-run]{RESET} would verify-push and print wiring instructions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
